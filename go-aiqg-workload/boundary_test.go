func user(text string) BoundaryMessage  { return BoundaryMessage{Role: "user", Text: text} }
func agent(text string) BoundaryMessage { return BoundaryMessage{Role: "assistant", Text: text} }
func toolResult(n int) BoundaryMessage  { return BoundaryMessage{Role: "user", ToolResults: n} }
func reminder(s string) string          { return "<system-reminder>" + s + "</system-reminder>" }

func TestClassifyMessage(t *testing.T) {
	cases := []struct {
		m    BoundaryMessage
		want MessageKind
	}{
		{user("fix the flaky test"), KindHuman},
		{user(reminder("today is Tuesday") + "\nyes go ahead"), KindHuman},
		{user(reminder("only a reminder")), KindEmpty},
		{user("   "), KindEmpty},
		{toolResult(1), KindToolResult},
		{BoundaryMessage{Role: "user", Text: "also check the logs", ToolResults: 2}, KindToolResult},
		{user("<command-name>/clear</command-name>"), KindInjected},
		{user("<local-command-stdout>ok</local-command-stdout>"), KindInjected},
		{user("<task-notification>agent finished</task-notification>"), KindInjected},
		{user("Caveat: the messages below were generated by the user while running local commands."), KindInjected},
		{user("[Request interrupted by user]"), KindInterrupt},
		{user("This session is being continued from a previous conversation that ran out of context."), KindContinuation},
		{user("<pasted_content>stack trace here</pasted_content>"), KindHuman},
		{agent("Done. Want me to open the PR?"), KindAgent},
		{BoundaryMessage{Role: "system", Text: "you are"}, KindAgent},
		{BoundaryMessage{Role: "tool", Text: "output"}, KindAgent},
		{BoundaryMessage{Role: "User", Text: "case-insensitive role"}, KindHuman},
	}
	for _, c := range cases {
		if got := ClassifyMessage(c.m); got != c.want {
			t.Errorf("%+v: got %s want %s", c.m, got, c.want)
		}
	}
}

func TestExtractTurnBoundary(t *testing.T) {
	cases := []struct {
		name      string
		msgs      []BoundaryMessage
		start     bool
		kind      MessageKind
		index     int
		continued bool
	}{
		{"empty", nil, false, KindEmpty, 0, false},
		{"first turn", []BoundaryMessage{user("add a health check")}, true, KindHuman, 1, false},
		{"mid-turn tool loop", []BoundaryMessage{user("add a health check"), agent(""), toolResult(1)}, false, KindToolResult, 1, false},
		{"second turn", []BoundaryMessage{user("add a health check"), agent(""), toolResult(1), agent("Done, want a test?"), user("yes")}, true, KindHuman, 2, false},
		{"reminder-only tail is not a turn", []BoundaryMessage{user("a"), agent("b"), user(reminder("x"))}, false, KindEmpty, 1, false},
		{"command echo is not a turn", []BoundaryMessage{user("a"), agent("b"), user("<command-name>/cost</command-name>")}, false, KindInjected, 1, false},
		{"interrupt is not a turn", []BoundaryMessage{user("a"), agent("b"), user("[Request interrupted by user]")}, false, KindInterrupt, 1, false},
		{"after compaction", []BoundaryMessage{user("This session is being continued from a previous conversation ..."), agent("ok"), user("now deploy it")}, true, KindHuman, 2, true},
		{"compaction alone starts a turn", []BoundaryMessage{user("This session is being continued from a previous conversation ...")}, true, KindContinuation, 1, true},
		{"ends on the agent", []BoundaryMessage{user("a"), agent("b")}, false, KindAgent, 1, false},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			b := ExtractTurnBoundary(c.msgs)
			if b.TurnStart != c.start || b.Kind != c.kind || b.TurnIndex != c.index || b.Continuation != c.continued || b.Version != TurnBoundaryVersion {
				t.Fatalf("got %+v want start=%v kind=%s index=%d continued=%v", b, c.start, c.kind, c.index, c.continued)
			}
		})
	}
}

func TestStripSystemReminders(t *testing.T) {
	if got := StripSystemReminders("a " + reminder("x") + " b " + reminder("y")); got != "a  b" {
		t.Fatalf("got %q", got)
	}
	// Unterminated: everything after the opening tag is dropped, never read as the human's text.
	if got := StripSystemReminders("keep <system-reminder>injected and never closed"); got != "keep" {
		t.Fatalf("got %q", got)
	}
}

func TestTurnBoundaryCarriesNoText(t *testing.T) {
	b := ExtractTurnBoundary([]BoundaryMessage{agent("the payroll export for acme"), user("ship the acme payroll fix")})
	raw, _ := json.Marshal(b)
	for _, w := range []string{"acme", "payroll", "ship"} {
		if strings.Contains(string(raw), w) {
			t.Fatalf("boundary contains %q: %s", w, raw)
		}
	}
}

func BenchmarkExtractTurnBoundary(b *testing.B) {
	msgs := make([]BoundaryMessage, 0, 200)
	for i := 0; i < 50; i++ {
		msgs = append(msgs, user(reminder(strings.Repeat("context ", 50))+"do the next step"), agent("ok"), toolResult(1), agent("done"))
	}
	b.ReportAllocs()
	for i := 0; i < b.N; i++ {
		ExtractTurnBoundary(msgs)
	}
}
